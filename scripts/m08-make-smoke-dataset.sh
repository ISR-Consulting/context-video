#!/usr/bin/env bash
# Builds the synthetic poc-smoke dataset: one 20 s clip generated locally
# (drawn football scoreboard + Portuguese text-to-speech), its manifest and a
# ground truth describing only what this script generated. It contains no
# third-party content and is NOT part of the Golden Dataset; use it to prove
# the M08 pipeline end to end on any host.
#
# usage: scripts/m08-make-smoke-dataset.sh [DATASET_ROOT]   (default ~/context-video-smoke)
set -euo pipefail

root="${1:-$HOME/context-video-smoke}"
id="smoke-synthetic"
duration=20
if [ -e "$root/manifests/poc-smoke-v0.1.json" ]; then
  echo "m08-make-smoke-dataset: $root already holds a smoke dataset" >&2
  exit 1
fi
mkdir -p "$root/media" "$root/manifests" "$root/ground-truth/poc-smoke"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

text="Bem-vindos à transmissão ao vivo. O time azul enfrenta o time vermelho. Gol do time azul! Que jogada bonita do camisa dez."
if command -v espeak-ng >/dev/null 2>&1; then
  espeak-ng -v pt-br -s 150 -w "$tmp/speech.wav" "$text"
elif command -v say >/dev/null 2>&1; then
  say -v Luciana -o "$tmp/speech.aiff" "$text" && ffmpeg -loglevel error -y -i "$tmp/speech.aiff" "$tmp/speech.wav"
else
  echo "m08-make-smoke-dataset: no espeak-ng or say; using a tone instead of speech" >&2
  ffmpeg -loglevel error -y -f lavfi -i "sine=frequency=440:duration=$duration" "$tmp/speech.wav"
fi

video_filter="drawbox=x=0:y=0:w=iw:h=90:color=black@0.7:t=fill,\
drawtext=font=Sans:text='AO VIVO  AZUL 1 x 0 VERMELHO':fontcolor=white:fontsize=48:x=40:y=20,\
drawbox=x=620:y=90:w=40:h=630:color=white@0.9:t=fill,\
drawtext=font=Sans:text='FUTEBOL':fontcolor=white:fontsize=96:x=(w-text_w)/2:y=h/2"
out="$root/media/$id.mp4"
encode() {
  ffmpeg -loglevel error -y -f lavfi -i "color=c=0x2e7d32:s=1280x720:r=25:d=$duration" -i "$tmp/speech.wav" \
    -filter_complex "[0:v]$1[v];[1:a]apad,atrim=0:$duration[a]" -map "[v]" -map "[a]" -t "$duration" \
    -c:v libx264 -preset veryfast -crf 23 -pix_fmt yuv420p -c:a aac -ar 48000 -ac 2 -movflags +faststart "$out"
}
if ! encode "$video_filter" 2>"$tmp/ffmpeg.log"; then
  echo "m08-make-smoke-dataset: text overlay unavailable ($(tail -1 "$tmp/ffmpeg.log")); using boxes only" >&2
  encode "drawbox=x=0:y=0:w=iw:h=90:color=black@0.7:t=fill,drawbox=x=620:y=90:w=40:h=630:color=white@0.9:t=fill"
fi

sha() { if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi; }
# durationMs is the shortest stream, floored, so no window reaches past either stream.
duration_ms="$(ffprobe -v error -show_entries stream=duration -of csv=p=0 "$out" |
  awk 'NR==1||$1<m{m=$1} END{printf "%d", m*1000}')"
digest="$(sha "$out")"

cat >"$root/manifests/poc-smoke-v0.1.json" <<EOF
{
  "schemaVersion": "1.0",
  "datasetId": "poc-smoke",
  "datasetVersion": "0.1",
  "name": "POC synthetic smoke dataset",
  "description": "Locally generated clip for M08 pipeline smoke runs. Not the Golden Dataset; results are not evaluation evidence.",
  "annotationGuidelinesVersion": "1.0",
  "testCases": [
    {
      "testCaseId": "$id",
      "scenario": "FOOTBALL_SPORTS_APPAREL",
      "content": {"contentId": "smoke-synthetic-001", "contentType": "VOD"},
      "media": {"kind": "LOCAL", "uri": "media/$id.mp4", "sha256": "$digest", "durationMs": $duration_ms},
      "groundTruthPath": "ground-truth/poc-smoke/$id.json",
      "description": "Generated by scripts/m08-make-smoke-dataset.sh: green pitch, scoreboard 'AZUL 1 x 0 VERMELHO', pt-BR synthetic speech about a goal.",
      "tags": ["synthetic", "smoke"]
    }
  ]
}
EOF
cat >"$root/ground-truth/poc-smoke/$id.json" <<EOF
{
  "schemaVersion": "1.0",
  "testCaseId": "$id",
  "content": {"contentId": "smoke-synthetic-001", "contentType": "VOD"},
  "annotations": [
    {
      "annotationId": "$id-0001",
      "window": {"startMs": 0, "endMs": $duration_ms},
      "expected": {"required": {"topics": ["football"]}},
      "annotatorNote": "Synthetic smoke clip. Labels describe only what the generator drew and spoke; it is not evaluation data."
    }
  ]
}
EOF
echo "smoke dataset: $root (media $out, ${duration_ms} ms, sha256 $digest)"
echo "manifest: manifests/poc-smoke-v0.1.json (relative to --dataset-root $root)"
